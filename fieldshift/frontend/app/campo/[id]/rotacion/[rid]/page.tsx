"use client";

import Link from "next/link";
import { useParams } from "next/navigation";
import { ArrowDown, ArrowLeft, ArrowUp, CalendarDays, CheckCircle2, Flag, Minus, ShieldAlert, TrendingDown, TrendingUp, TriangleAlert } from "lucide-react";
import { useCampo } from "@/components/campo/campo-provider";
import { PageHeader } from "@/components/page-header";
import { ConfidenceBadge, LabelBadge, RiskLevelBadge, SeverityBadge, flagIcon } from "@/components/provenance/badges";
import { ScoreBars } from "@/components/score/score-bars";
import { SoilRoles } from "@/components/agronomy/soil-roles";
import { Alert } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { COMPONENTS, COMPONENT_ORDER, CONFIDENCE_LABELS, LEVEL_LABELS, STRATEGY_LABELS, num, rotationTitle, signed } from "@/lib/format";
import type { RotationEvaluation, ScoreDriver } from "@/types/api";
import { L, localize, tr } from "@/lib/i18n";

const IMPACT_ICON = { mejora: TrendingUp, empeora: TrendingDown, neutro: Minus, linea_base: Flag } as const;
const IMPACT_TEXT: Record<"mejora" | "empeora" | "neutro" | "linea_base", string> = localize({ mejora: L("Mejora", "Improves"), empeora: L("Empeora", "Worsens"), neutro: L("Similar", "Similar"), linea_base: L("Punto de partida", "Starting point") });

function Impact({ label, impact }: { label: string; impact: { direction: keyof typeof IMPACT_ICON; detail: string } }) {
  const Icon = IMPACT_ICON[impact.direction];
  return (
    <div className="flex gap-3">
      <Icon aria-hidden className="mt-1 size-5 shrink-0" />
      <div>
        <p className="font-medium">{label}: {IMPACT_TEXT[impact.direction]}</p>
        <p className="text-sm text-muted-foreground">{impact.detail}</p>
      </div>
    </div>
  );
}

const EFFECT = { sube: { Icon: ArrowUp, text: () => tr("Suma", "Adds") }, baja: { Icon: ArrowDown, text: () => tr("Resta", "Subtracts") }, neutro: { Icon: Minus, text: () => tr("Informa", "Info") } } as const;

function DriverRow({ d }: { d: ScoreDriver }) {
  const e = EFFECT[d.effect as keyof typeof EFFECT] ?? EFFECT.neutro;
  return (
    <TableRow>
      <TableCell className="min-w-40 font-medium">{d.factor}</TableCell>
      <TableCell className="whitespace-nowrap">
        <span className="inline-flex items-center gap-1"><e.Icon aria-hidden className="size-4" /> {e.text()} {d.points != null && d.effect !== "neutro" ? `${signed(d.points, 1)} pts` : ""}</span>
      </TableCell>
      <TableCell className="min-w-64 text-sm">{d.detail}</TableCell>
      <TableCell><LabelBadge label={d.provenance.label} /></TableCell>
    </TableRow>
  );
}

function Detail({ ev, fieldId }: { ev: RotationEvaluation; fieldId: string }) {
  const { compare } = useCampo();
  const result = compare.result;
  const { rotation: r, profile: p, score, recommendation: rec } = ev;
  const sources = result?.sources.filter((s) => ev.source_ids.includes(s.id)) ?? [];
  const e4 = rec.evidence;
  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center gap-2">
        <Badge variant="secondary" className="text-base">{tr(`Puesto ${score.rank} de ${compare.evaluations.length}`, `Rank ${score.rank} of ${compare.evaluations.length}`)}</Badge>
        <Badge variant="outline">{STRATEGY_LABELS[r.strategy]}</Badge>
        <RiskLevelBadge level={score.risk_level} />
        <ConfidenceBadge level={ev.confidence} />
        <Badge variant="outline">{r.origin === "declarada" ? tr("Rotación declarada", "Declared rotation") : tr("Generada por AgroOrbit", "Generated by AgroOrbit")}</Badge>
      </div>

      <Card className="border-primary/40 bg-primary/5">
        <CardContent className="flex flex-wrap items-center gap-x-8 gap-y-4 pt-5">
          <p><span className="text-6xl font-bold tabular-nums">{num(score.total)}</span><span className="text-xl text-muted-foreground"> / 100</span></p>
          <div className="min-w-64 flex-1"><ScoreBars components={score.components} showWeights /></div>
        </CardContent>
        <CardContent className="pt-0 text-sm text-muted-foreground">
          {tr(`Rango probable: ${num(score.uncertainty_low)} a ${num(score.uncertainty_high)}. Cambia con la lluvia (±15 %) y con la calidad de los datos.`, `Likely range: ${num(score.uncertainty_low)} to ${num(score.uncertainty_high)}. It changes with rainfall (±15 %) and data quality.`)}
        </CardContent>
      </Card>

      <Card>
        <CardHeader><CardTitle as="h2">{tr("Por qué", "Why")}</CardTitle></CardHeader>
        <CardContent className="space-y-3 text-lg">
          <p>{rec.why}</p>
          {r.description && <p className="text-base text-muted-foreground">{r.description}</p>}
        </CardContent>
      </Card>

      <SoilRoles cropIds={r.steps.map((st) => st.crop_id)} />

      <div className="grid gap-4 md:grid-cols-2">
        <Card>
          <CardHeader><CardTitle as="h2" className="flex items-center gap-2"><CheckCircle2 aria-hidden className="size-5 text-cultivo-600" /> {tr("Beneficios", "Benefits")}</CardTitle></CardHeader>
          <CardContent>
            {rec.benefits.length ? <ul className="list-disc space-y-1.5 pl-5">{rec.benefits.map((b) => <li key={b}>{b}</li>)}</ul> : <p className="text-muted-foreground">{tr("No mejora ningún aspecto clave frente a la rotación actual.", "It does not improve any key aspect over the current rotation.")}</p>}
          </CardContent>
        </Card>
        <Card>
          <CardHeader><CardTitle as="h2" className="flex items-center gap-2"><TriangleAlert aria-hidden className="size-5 text-tierra-600" /> {tr("Riesgos", "Risks")}</CardTitle></CardHeader>
          <CardContent>
            <ul className="space-y-3">
              {ev.risk_flags.length === 0 && <li className="text-muted-foreground">{tr("Sin riesgos destacados con los datos disponibles.", "No notable risks with the available data.")}</li>}
              {ev.risk_flags.map((f) => {
                const Icon = flagIcon(f.icon);
                return (
                  <li key={f.id} className="flex gap-3">
                    <Icon aria-hidden className="mt-1 size-5 shrink-0" />
                    <div className="space-y-1">
                      <SeverityBadge severity={f.severity} />
                      <p>{f.message}</p>
                      {f.evidence.length > 0 && <p className="text-sm text-muted-foreground">{f.evidence.join(" ")}</p>}
                    </div>
                  </li>
                );
              })}
            </ul>
          </CardContent>
        </Card>
      </div>

      <Card>
        <CardHeader>
          <CardTitle as="h2">{tr("Qué implica", "What it involves")}</CardTitle>
          <CardDescription>{p.sequence.join(" → ")} · {tr(`ciclo de ${p.duration_years} ${p.duration_years === 1 ? "año" : "años"} · ${p.distinct_crops} cultivos distintos`, `${p.duration_years}-year cycle · ${p.distinct_crops} distinct crops`)}</CardDescription>
        </CardHeader>
        <CardContent className="grid gap-5 md:grid-cols-2">
          <div className="space-y-1">
            <p className="font-medium">{tr("Agua", "Water")}</p>
            <p>{tr(<>Demanda estimada de los cultivos: <strong>{num(p.water_demand_mm_year)} mm por año</strong> (requerimiento {LEVEL_LABELS[p.water_requirement].toLowerCase()}).</>, <>Estimated crop demand: <strong>{num(p.water_demand_mm_year)} mm per year</strong> ({LEVEL_LABELS[p.water_requirement].toLowerCase()} requirement).</>)}</p>
            <p>{tr(<>La lluvia y el agua guardada en el suelo cubren el <strong>{num(p.rain_coverage_pct)} %</strong>; falta cubrir {num(p.deficit_mm_year)} mm por año{p.irrigation_mm_year ? `, y con riego se aplican unos ${num(p.irrigation_mm_year)} mm` : ""}.</>, <>Rain and water stored in the soil cover <strong>{num(p.rain_coverage_pct)} %</strong>; {num(p.deficit_mm_year)} mm per year is still uncovered{p.irrigation_mm_year ? `, and irrigation applies about ${num(p.irrigation_mm_year)} mm` : ""}.</>)}</p>
            {p.relative_water_demand != null && r.strategy !== "actual" && <p className="text-sm text-muted-foreground">{tr(`Es el ${num(p.relative_water_demand * 100)} % de la demanda de tu rotación actual.`, `It is ${num(p.relative_water_demand * 100)} % of your current rotation's demand.`)}</p>}
          </div>
          <div className="space-y-1">
            <p className="font-medium">{tr("Cobertura del suelo", "Soil cover")}</p>
            <p>{tr(<>Hay cultivo vivo el <strong>{num(p.covered_months_pct)} %</strong> del tiempo; el suelo queda sin cultivo <strong>{num(p.bare_months_per_year, 1)} meses por año</strong>.</>, <>There is a living crop <strong>{num(p.covered_months_pct)} %</strong> of the time; the soil has no crop <strong>{num(p.bare_months_per_year, 1)} months per year</strong>.</>)}</p>
            <p className="text-sm text-muted-foreground">{tr("Ingreso relativo", "Relative income")}: <strong>{LEVEL_LABELS[p.relative_income]}</strong> · {tr("Complejidad de implementación", "Implementation complexity")}: <strong>{LEVEL_LABELS[p.implementation_complexity]}</strong> · {tr("Riesgo de erosión", "Erosion risk")}: <strong>{LEVEL_LABELS[p.erosion_risk]}</strong></p>
          </div>
          <Impact label={tr("Suelo", "Soil")} impact={p.soil_impact} />
          <Impact label={tr("Erosión", "Erosion")} impact={p.erosion_impact} />
          <Impact label={tr("Biodiversidad", "Biodiversity")} impact={p.biodiversity_impact} />
          <div>
            <Button asChild variant="outline">
              <Link href={`/campo/${fieldId}/calendario?rotacion=${encodeURIComponent(r.id)}`}><CalendarDays aria-hidden /> {tr("Ver el calendario de siembra", "See the planting calendar")}</Link>
            </Button>
          </div>
        </CardContent>
        {r.management.length > 0 && (
          <CardContent>
            <p className="font-medium">{tr("Para implementarla hace falta:", "To implement it you need:")}</p>
            <ul className="mt-1 list-disc space-y-1 pl-5">{r.management.map((m) => <li key={m}>{m}</li>)}</ul>
          </CardContent>
        )}
      </Card>

      <section aria-labelledby="desglose" className="space-y-4">
        <h2 id="desglose" className="text-2xl font-semibold">{tr("Cómo se armó el puntaje", "How the score was built")}</h2>
        <p className="text-muted-foreground">{tr("Cada componente parte de datos y suma o resta puntos por motivos concretos. El total es la suma ponderada con tus prioridades.", "Each component starts from data and adds or subtracts points for concrete reasons. The total is the sum weighted by your priorities.")}</p>
        {COMPONENT_ORDER.map((k) => {
          const c = score.components.find((x) => x.key === k);
          if (!c) return null;
          return (
            <Card key={k}>
              <CardHeader>
                <CardTitle className="flex flex-wrap items-baseline gap-x-3 text-lg">
                  <span>{k} · {COMPONENTS[k].name}</span>
                  <span className="tabular-nums">{num(c.value)}/100</span>
                  <span className="text-sm font-normal text-muted-foreground">{tr(`peso ${num(c.weight * 100)} % → aporta ${num((c.value ?? 0) * c.weight, 1)} puntos al total`, `weight ${num(c.weight * 100)} % → adds ${num((c.value ?? 0) * c.weight, 1)} points to the total`)}</span>
                </CardTitle>
                <CardDescription>{COMPONENTS[k].help}</CardDescription>
              </CardHeader>
              <CardContent>
                <Table scrollLabel={tr(`Motivos del puntaje de ${COMPONENTS[k].name}: desplazá para ver todo`, `Reasons for the ${COMPONENTS[k].name} score: scroll to see everything`)}>
                  <TableHeader>
                    <TableRow><TableHead>{tr("Factor", "Factor")}</TableHead><TableHead>{tr("Efecto", "Effect")}</TableHead><TableHead>{tr("Detalle", "Detail")}</TableHead><TableHead>{tr("Tipo de dato", "Data type")}</TableHead></TableRow>
                  </TableHeader>
                  <TableBody>{c.drivers.map((d, i) => <DriverRow key={`${d.factor}-${i}`} d={d} />)}</TableBody>
                </Table>
              </CardContent>
            </Card>
          );
        })}
      </section>

      <section aria-labelledby="evidencia" className="space-y-4">
        <h2 id="evidencia" className="text-2xl font-semibold">{tr("De dónde sale cada cosa", "Where each thing comes from")}</h2>
        <div className="grid gap-4 md:grid-cols-2">
          {([
            [tr("Lo que muestran los datos de la NASA", "What NASA data shows"), e4.nasa_data],
            [tr("Lo que depende de tu suelo", "What depends on your soil"), e4.local_soil],
            [tr("Lo que depende de vos", "What depends on you"), e4.producer],
            [tr("Lo que hay que validar con un agrónomo", "What an agronomist must validate"), e4.needs_validation],
          ] as const).map(([title, items]) => (
            <Card key={title}>
              <CardHeader><CardTitle className="text-lg">{title}</CardTitle></CardHeader>
              <CardContent><ul className="list-disc space-y-1.5 pl-5">{items.map((x) => <li key={x}>{x}</li>)}</ul></CardContent>
            </Card>
          ))}
        </div>
      </section>

      <section aria-labelledby="limites" className="grid gap-4 md:grid-cols-3">
        <h2 id="limites" className="sr-only">{tr("Supuestos e incertidumbres", "Assumptions and uncertainties")}</h2>
        <Card><CardHeader><CardTitle className="text-lg">{tr("Supuestos", "Assumptions")}</CardTitle></CardHeader><CardContent><ul className="list-disc space-y-1.5 pl-5 text-sm">{rec.assumptions.map((t) => <li key={t}>{t}</li>)}</ul></CardContent></Card>
        <Card><CardHeader><CardTitle className="text-lg">{tr("Incertidumbres", "Uncertainties")}</CardTitle></CardHeader><CardContent><ul className="list-disc space-y-1.5 pl-5 text-sm">{rec.uncertainties.map((t) => <li key={t}>{t}</li>)}</ul></CardContent></Card>
        <Card><CardHeader><CardTitle className="text-lg">{tr("Datos que mejorarían el resultado", "Data that would improve the result")}</CardTitle></CardHeader><CardContent>{rec.information_gaps.length ? <ul className="list-disc space-y-1.5 pl-5 text-sm">{rec.information_gaps.map((t) => <li key={t}>{t}</li>)}</ul> : <p className="text-sm text-muted-foreground">{tr("No faltan datos clave.", "No key data is missing.")}</p>}</CardContent></Card>
      </section>

      {ev.confidence_reasons.length > 0 && (
        <Alert tone="info" title={tr(`Por qué la confianza es ${ev.confidence}`, `Why confidence is ${CONFIDENCE_LABELS[ev.confidence].split(" ").pop()}`)}>
          <ul className="list-disc space-y-1 pl-5">{ev.confidence_reasons.map((t) => <li key={t}>{t}</li>)}</ul>
        </Alert>
      )}
      <Alert tone="warning" title={tr("Validá esto con un profesional", "Check this with a professional")}>
        <p>{rec.validation_note}</p>
        <p className="text-sm">{rec.disclaimer}</p>
      </Alert>

      {sources.length > 0 && (
        <details className="rounded-lg border p-4">
          <summary className="flex cursor-pointer items-center gap-2 font-medium"><ShieldAlert aria-hidden className="size-4" /> {tr("Fuentes usadas", "Sources used")} ({sources.length})</summary>
          <ul className="mt-3 space-y-3 text-sm">
            {sources.map((s) => (
              <li key={s.id}>
                <p className="font-medium">{s.name}</p>
                <p className="text-muted-foreground">{s.provider}{s.product ? ` · ${s.product}` : ""} · {s.spatial_resolution} · {s.temporal_resolution}</p>
                <p className="text-muted-foreground">{s.citation}</p>
              </li>
            ))}
          </ul>
        </details>
      )}
    </div>
  );
}

export default function RotacionPage() {
  const params = useParams<{ id: string; rid: string }>();
  const { fieldId, compare } = useCampo();
  const rid = decodeURIComponent(params.rid);
  const ev = compare.evaluations.find((e) => e.rotation.id === rid);

  return (
    <div className="max-w-5xl">
      <Button variant="ghost" size="sm" asChild className="mb-3 -ml-3">
        <Link href={`/campo/${fieldId}/comparador`}><ArrowLeft aria-hidden /> {tr("Volver al comparador", "Back to the comparison")}</Link>
      </Button>
      {!ev && compare.error && !compare.result && <Alert tone="error" title={tr("No pudimos calcular esta rotación", "We couldn't calculate this rotation")}><p>{compare.error}</p><Button size="sm" variant="outline" onClick={compare.reload}>{tr("Reintentar", "Retry")}</Button></Alert>}
      {!ev && !compare.error && !compare.result && <div role="status" aria-busy="true"><span className="sr-only">{tr("Cargando la rotación…", "Loading the rotation…")}</span><Skeleton className="h-96 w-full" /></div>}
      {!ev && compare.result && (
        <Alert tone="warning" title={tr("No encontramos esta rotación", "We couldn't find this rotation")}>
          <p>{tr("Puede que ya no esté entre las opciones con tus datos actuales.", "It may no longer be among the options with your current data.")}</p>
          <Button size="sm" variant="outline" asChild><Link href={`/campo/${fieldId}/comparador`}>{tr("Ver las rotaciones disponibles", "See the available rotations")}</Link></Button>
        </Alert>
      )}
      {ev && (
        <>
          <PageHeader title={rotationTitle(ev.rotation)} description={tr("Detalle de la rotación: qué implica, por qué recibe este puntaje y qué hay que validar.", "Rotation details: what it involves, why it gets this score and what needs validating.")} />
          <Detail ev={ev} fieldId={fieldId} />
        </>
      )}
    </div>
  );
}
